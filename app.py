    """Route to add an email and start auto track"""

    email = request.form.get('email')

    if email:
        db = get_db()
        cur = db.cursor()
        cur.execute("UPDATE searches SET email = ? WHERE id = ?",
                    (email, search_id,))
        db.commit()

    return redirect('/autotrack')


