# Setting up a scheduled task to send out search results daily
def send_daily_search():
    """Iterates through the saved search list.  If email present: searches flights, and emails results"""

    with app.app_context():
        db = get_db()
        cur = db.cursor()
        cur.execute(
            "SELECT * FROM searches WHERE email IS NOT NULL AND email != ''")
        searches = cur.fetchall()

        for search in searches:
            response = get_flight_offers(
                origin=search['origin'],
                destination=search['destination'],
                departure_date=search['date'],
                adults=search['adults'],
                airline_code=search['airline'],
                max_results=search['results'],
                nonstop=search['nonstop']
            )

            if response is None:
                continue

            # Reformat date
            search_dict = dict(search)
            dt = datetime.fromisoformat(search_dict.get("date"))
            search_dict["date"] = dt.strftime("%a, %b %d, %Y")

            flight_data = process_flight_data(response)
            subject = f"Flight Offers {search['origin']}->{search['destination']} {search_dict['date']}"
            gmail_send_message(flight_data, search['email'], subject=subject)
