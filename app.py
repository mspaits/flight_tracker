AIRLINE_CODE_CACHE = {}

# Generated by Codex


def iso_duration_to_text(s):
    s = s.replace("PT", "")
    hours = minutes = 0
    if "H" in s:
        hours, s = s.split("H", 1)
        hours = int(hours or 0)
    if "M" in s:
        minutes = int(s.split("M", 1)[0] or 0)
    parts = []
    if hours:
        parts.append(f"{hours} hr")
    if minutes:
        parts.append(f"{minutes} min")
    return " ".join(parts) if parts else "0 min"


def get_airline_name(airline_code):
    """Function to look up airline name from 2-letter code"""
    if not airline_code or len(airline_code) != 2:
        return airline_code

    try:
        cached = AIRLINE_CODE_CACHE.get(airline_code)
        if cached:
            return cached

        airline_response = amadeus.reference_data.airlines.get(
            airlineCodes=airline_code)
        airline_name = airline_response.data[0]['commonName']
        AIRLINE_CODE_CACHE[airline_code] = airline_name
        return airline_name

    except ResponseError as error:
        print(f"An error occurred in airline lookup: {error}")
        return airline_code


def get_flight_offers(origin, destination, departure_date, adults, airline_code, max_results, nonstop):
    """Function to get flight offers from Amadeus API"""

    if departure_date < datetime.now().date().isoformat():
        print("Departure date is in the past.")
        return None

    try:
        params = dict(
            originLocationCode=origin,
            destinationLocationCode=destination,
            departureDate=departure_date,
            adults=adults,
            currencyCode='USD'
        )
        if airline_code:
            params['includedAirlineCodes'] = airline_code
        if max_results:
            params['max'] = int(max_results)
        if nonstop:
            params['nonStop'] = 'true'

        response = amadeus.shopping.flight_offers_search.get(**params)

        return response

    except ResponseError as error:
        print(
            f"An error occurred getting flight data, get_flight_offers failed: {error}")
        return None


def process_flight_data(response):
    """Function to process flight data from Amadeus response.  Pick needed data from JSON and create new list of dicts"""

    # Create an empty list to hold flight data for rendering in Flask
    flight_data = []

    for flight in response.data:
        legs = len(flight['itineraries'][0]['segments'])
        # Contains duration and segments
        itinerary = flight['itineraries'][0]
        # Contains each flight leg details
        segments = itinerary['segments']

        flight_info = {
            "search_no": flight['id'],
            "stops": (legs - 1),
            "departure_airport": segments[0]['departure']['iataCode'],
            "departure_time": segments[0]['departure']['at'],
            "arrival_airport": segments[-1]['arrival']['iataCode'],
            "arrival_time": segments[-1]['arrival']['at'],
            "duration": flight['itineraries'][0]['duration'],
            "carrier_code": flight['validatingAirlineCodes'][0],
            "price": flight['price']['grandTotal'],
            "bookable_seats": flight['numberOfBookableSeats'],
            "legs": []
        }

        for i in range(legs):
            flight_info_leg = {
                "leg_no": i + 1,
                "departure_airport": segments[i]['departure']['iataCode'],
                "departure_time": segments[i]['departure']['at'],
                "arrival_airport": segments[i]['arrival']['iataCode'],
                "arrival_time": segments[i]['arrival']['at'],
                "duration": segments[i]['duration'],
                "carrier_code": segments[i]['operating'].get('carrierCode') or
                segments[i]['operating'].get('carrierName'),
                "flight_number": segments[i]['number']
            }
            flight_info["legs"].append(flight_info_leg)

        flight_data.append(flight_info)

    # Iterate through flight dicts and update time and duration format, look up carrier.
    for flight in flight_data:
        dt = datetime.fromisoformat(flight.get("departure_time"))
        flight["departure_time"] = dt.strftime("%a, %b %d, %Y - %-I:%M %p")

        dt = datetime.fromisoformat(flight.get("arrival_time"))
        flight["arrival_time"] = dt.strftime("%a, %b %d, %Y - %-I:%M %p")

        flight["duration"] = iso_duration_to_text(flight.get('duration'))

        code = flight.get("carrier_code")

        if code:
            flight["carrier_code"] = get_airline_name(code)

        for leg in flight.get("legs", []):
            dt = datetime.fromisoformat(leg.get("departure_time"))
            leg["departure_time"] = dt.strftime("%a, %b %d, %Y - %-I:%M %p")

            dt = datetime.fromisoformat(leg.get("arrival_time"))
            leg["arrival_time"] = dt.strftime("%a, %b %d, %Y - %-I:%M %p")

            leg["duration"] = iso_duration_to_text(leg.get('duration'))

            code = leg.get("carrier_code")

            if code:
                leg["carrier_code"] = get_airline_name(code)

    # pprint(flight_data)

    return flight_data


# Straight up copied this from Codex.  Decided to do it the right way with OAuth2 and got in way deep.
def get_gmail_creds():

    SCOPES = ["https://www.googleapis.com/auth/gmail.send"]

    # SECRETS_DIR can be set in .env; otherwise default to "<app>/secrets"
    secrets_dir = os.getenv("SECRETS_DIR") or os.path.join(
        current_app.root_path, "secrets")

    secrets_dir = Path(secrets_dir)
    token_path = secrets_dir / "token.json"
    client_path = secrets_dir / "credentials.json"

    secrets_dir.mkdir(parents=True, exist_ok=True)

    creds = None
    if token_path.exists():
        creds = Credentials.from_authorized_user_file(str(token_path), SCOPES)

    if not creds or not creds.valid:
        if creds and creds.expired and creds.refresh_token:
            try:
                creds.refresh(Request())
            except Exception:
                creds = None
        if not creds or not creds.valid:
            flow = InstalledAppFlow.from_client_secrets_file(
                str(client_path), SCOPES)
            creds = flow.run_local_server(port=0)
        token_path.write_text(creds.to_json())

    return creds


# Create function to email out results.  From Google Gmail API quickstart.
def gmail_send_message(flight_data, to_email, subject=None):
    """Email flight offers using Gmail API"""

    creds = get_gmail_creds()

    try:
        service = build("gmail", "v1", credentials=creds)
        message = EmailMessage()

        message['To'] = to_email
        message['From'] = "mspaitsdev@gmail.com"
        message['Subject'] = subject or "Flight Offers"

        message.set_content("Flight offers (text fallback).")
        html_body = render_template("email_template.html", flights=flight_data)
        message.add_alternative(html_body, subtype="html")

        # Encode the message
        encoded_message = base64.urlsafe_b64encode(message.as_bytes()).decode()

        create_message = {'raw': encoded_message}
        # pyling: disable=E1101
        send_message = (service.users().messages().send(
            userId="me", body=create_message).execute())
        print(F'Message Id: {send_message["id"]}')

    except HttpError as error:
        print(f'An error occurred with mail: {error}')
        send_message = None
    return send_message


